export function validProgress(value) {
  return Array.isArray(value)
    ? [
        ...new Set(
          value.filter(
            (id) => missions.some((m) => m.id === id) || id === "quiz",
          ),
        ),
      ]
    : [];
}
export function mergeProgress(a, b) {
  return validProgress([...validProgress(a), ...validProgress(b)]);
}
export function pointsFor(done) {
  return validProgress(done).length * 30;
}
